import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { BountyOSClient } from "../client.js";
import { globalPolicyEngine } from "../policy/engine.js";
import { McpLogger } from "../policy/logger.js";
import { McpErrorCode, mcpErrorResponse, mcpSuccessResponse } from "../schemas/errors.js";

export function registerIntelligenceTools(server: McpServer, client: BountyOSClient) {
  // 1. intelligence.context
  server.tool(
    "intelligence.context",
    "Extract bounded structured strategic context (target, scope, assets, services, endpoints, parameters, technologies, coverage gaps, existing findings, action values, candidate actions) for VulnLLM reasoning.",
    {
      investigation_id: z.string().describe("The UUID of the investigation"),
    },
    async ({ investigation_id }) => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const context = await client.getInvestigationContext(investigation_id);

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "intelligence.context",
          arguments: { investigation_id },
          investigation_id,
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(context);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to retrieve strategic context: ${e.message}`
        );
      }
    }
  );

  // 2. intelligence.hypothesize
  server.tool(
    "intelligence.hypothesize",
    "Submit and validate structured security hypotheses generated by VulnLLM. Untrusted input is strictly validated: targets not existing in the graph or out of scope are REJECTED.",
    {
      investigation_id: z.string().describe("The UUID of the investigation"),
      hypotheses: z
        .array(
          z.object({
            category: z.string().describe("Vulnerability hypothesis category (e.g. xss, exposed_admin, sqli)"),
            target: z.string().describe("Target endpoint or host within the investigation attack surface graph"),
            rationale: z.string().describe("Structured reasoning and justification for the hypothesis"),
            confidence: z.number().min(0.0).max(1.0).default(0.7).describe("Confidence score [0.0 - 1.0]"),
            suggested_actions: z.array(z.string()).default([]).describe("Suggested legal action types"),
            required_evidence: z.array(z.string()).default([]).describe("Empirical evidence required to validate"),
          })
        )
        .describe("List of security hypotheses to evaluate and register"),
    },
    async ({ investigation_id, hypotheses }) => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const res = await client.submitInvestigationHypotheses(investigation_id, hypotheses);

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "intelligence.hypothesize",
          arguments: { investigation_id, count: hypotheses.length },
          investigation_id,
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(res);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to process security hypotheses: ${e.message}`
        );
      }
    }
  );

  // 3. intelligence.prioritize
  server.tool(
    "intelligence.prioritize",
    "Rank investigation directions using VulnLLM strategic hypothesis priorities, computing bounded priority boosts for the deterministic planner.",
    {
      investigation_id: z.string().describe("The UUID of the investigation"),
      hypotheses: z
        .array(
          z.object({
            category: z.string().describe("Hypothesis category (e.g. xss, exposed_admin)"),
            priority: z.number().min(0.0).max(1.0).describe("Priority rating [0.0 - 1.0]"),
            target: z.string().describe("Target endpoint or host"),
          })
        )
        .describe("Ranked list of investigation directions"),
    },
    async ({ investigation_id, hypotheses }) => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const res = await client.prioritizeInvestigation(investigation_id, hypotheses);

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "intelligence.prioritize",
          arguments: { investigation_id, count: hypotheses.length },
          investigation_id,
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(res);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to prioritize investigation directions: ${e.message}`
        );
      }
    }
  );

  // 4. experience.actions (v0.6)
  server.tool(
    "experience.actions",
    "Retrieve cross-investigation global experience actions, empirical values V(a | archetype, technology), sample counts, and success rates.",
    {},
    async () => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const actions = await client.getExperienceActions();

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "experience.actions",
          arguments: {},
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(actions);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to retrieve global experience actions: ${e.message}`
        );
      }
    }
  );

  // 5. experience.provenance (v0.6)
  server.tool(
    "experience.provenance",
    "Query the provenance audit trail for learned empirical action values: traces experience value -> investigation ID -> action ID -> job ID -> evidence.",
    {
      archetype: z.string().optional().describe("Optional target archetype filter (e.g. rest_api, web_legacy)"),
      tool: z.string().optional().describe("Optional tool filter (e.g. katana, ffuf, nuclei)"),
    },
    async ({ archetype, tool }) => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const provenance = await client.getExperienceProvenance({ archetype, tool });

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "experience.provenance",
          arguments: { archetype, tool },
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(provenance);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to query experience provenance: ${e.message}`
        );
      }
    }
  );

  // 6. investigation.archetype (v0.6)
  server.tool(
    "investigation.archetype",
    "Retrieve the dynamic target archetype classification, confidence score, and supporting evidence for an investigation.",
    {
      investigation_id: z.string().describe("The UUID of the investigation"),
    },
    async ({ investigation_id }) => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const archetype = await client.getInvestigationArchetype(investigation_id);

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "investigation.archetype",
          arguments: { investigation_id },
          investigation_id,
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(archetype);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to retrieve target archetype: ${e.message}`
        );
      }
    }
  );

  // 7. investigation.profile (v0.7)
  server.tool(
    "investigation.profile",
    "Retrieve the normalized target attack-surface profile (technologies, services, auth state, indicators, and confidence) derived from observed evidence.",
    {
      investigation_id: z.string().describe("The UUID of the investigation"),
    },
    async ({ investigation_id }) => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const profile = await client.getInvestigationProfile(investigation_id);

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "investigation.profile",
          arguments: { investigation_id },
          investigation_id,
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(profile);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to retrieve target profile: ${e.message}`
        );
      }
    }
  );

  // 8. investigation.policy (v0.7)
  server.tool(
    "investigation.policy",
    "Retrieve the active target-specific investigation policy, candidate action prioritizations, and self-explaining decision provenance.",
    {
      investigation_id: z.string().describe("The UUID of the investigation"),
    },
    async ({ investigation_id }) => {
      const startTime = Date.now();
      const requestId = McpLogger.createRequestId();

      try {
        const policy = await client.getInvestigationPolicy(investigation_id);

        McpLogger.logOperation({
          request_id: requestId,
          actor: "agent",
          tool: "investigation.policy",
          arguments: { investigation_id },
          investigation_id,
          duration_ms: Date.now() - startTime,
          result: "SUCCESS",
        });

        return mcpSuccessResponse(policy);
      } catch (e: any) {
        return mcpErrorResponse(
          McpErrorCode.INTERNAL_ERROR,
          `Failed to retrieve investigation policy: ${e.message}`
        );
      }
    }
  );
}

