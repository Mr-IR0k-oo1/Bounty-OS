//! Planned and Candidate Actions Model
//!
//! Defines typed actions emitted by the intelligence planner.
//! The intelligence layer does not execute commands; it produces a typed `PlannedAction`.
//! The existing runner/adapter translates planned actions into real tool invocations.

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fmt;
use uuid::Uuid;

/// Typed action categories produced by the intelligence engine
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Hash)]
#[serde(rename_all = "snake_case")]
pub enum ActionType {
    SubdomainEnumeration,
    DnsResolution,
    PortScan,
    HttpProbe,
    EndpointCrawl,
    HistoricalUrls,
    PathFuzz,
    TechVulnerabilityScan,
    XssAnalysis,
    FindingVerification,
    Stop,
}

impl ActionType {
    pub fn as_str(&self) -> &'static str {
        match self {
            ActionType::SubdomainEnumeration => "subdomain_enumeration",
            ActionType::DnsResolution => "dns_resolution",
            ActionType::PortScan => "port_scan",
            ActionType::HttpProbe => "http_probe",
            ActionType::EndpointCrawl => "endpoint_crawl",
            ActionType::HistoricalUrls => "historical_urls",
            ActionType::PathFuzz => "path_fuzz",
            ActionType::TechVulnerabilityScan => "tech_vulnerability_scan",
            ActionType::XssAnalysis => "xss_analysis",
            ActionType::FindingVerification => "finding_verification",
            ActionType::Stop => "stop",
        }
    }
}

impl fmt::Display for ActionType {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

/// A candidate action generated by the candidate generator prior to final scoring
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct CandidateAction {
    pub action_type: ActionType,
    pub tool: String,
    pub target: String,
    pub reason: String,
    pub info_gain: f64,
    pub relevance: f64,
    pub confidence: f64,
    pub cost: f64,
    pub risk: f64,
    pub context: HashMap<String, String>,
}

impl CandidateAction {
    pub fn new(
        action_type: ActionType,
        tool: impl Into<String>,
        target: impl Into<String>,
        reason: impl Into<String>,
    ) -> Self {
        Self {
            action_type,
            tool: tool.into(),
            target: target.into(),
            reason: reason.into(),
            info_gain: 0.5,
            relevance: 0.5,
            confidence: 0.5,
            cost: 0.2,
            risk: 0.1,
            context: HashMap::new(),
        }
    }

    pub fn with_metrics(
        mut self,
        info_gain: f64,
        relevance: f64,
        confidence: f64,
        cost: f64,
        risk: f64,
    ) -> Self {
        self.info_gain = info_gain;
        self.relevance = relevance;
        self.confidence = confidence;
        self.cost = cost;
        self.risk = risk;
        self
    }

    pub fn with_context(mut self, key: impl Into<String>, value: impl Into<String>) -> Self {
        self.context.insert(key.into(), value.into());
        self
    }
}

/// A finalized planned action recommended by the intelligence engine
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PlannedAction {
    pub id: String,
    pub action_type: ActionType,
    pub tool: String,
    pub target: String,
    pub reason: String,
    pub score: f64,
    pub info_gain: f64,
    pub relevance: f64,
    pub confidence: f64,
    pub cost: f64,
    pub risk: f64,
    pub context: HashMap<String, String>,
}

impl PlannedAction {
    pub fn new(
        action_type: ActionType,
        tool: impl Into<String>,
        target: impl Into<String>,
        reason: impl Into<String>,
        score: f64,
    ) -> Self {
        let (ig, r, c, cost, risk) = crate::intelligence::scoring::ActionScorer::default_metrics(action_type);
        Self {
            id: Uuid::new_v4().to_string(),
            action_type,
            tool: tool.into(),
            target: target.into(),
            reason: reason.into(),
            score: (score * 100.0).round() / 100.0,
            info_gain: ig,
            relevance: r,
            confidence: c,
            cost,
            risk,
            context: HashMap::new(),
        }
    }

    pub fn with_metrics(
        mut self,
        info_gain: f64,
        relevance: f64,
        confidence: f64,
        cost: f64,
        risk: f64,
    ) -> Self {
        self.info_gain = info_gain;
        self.relevance = relevance;
        self.confidence = confidence;
        self.cost = cost;
        self.risk = risk;
        self
    }

    pub fn stop(reason: impl Into<String>) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            action_type: ActionType::Stop,
            tool: "none".to_string(),
            target: "".to_string(),
            reason: reason.into(),
            score: 0.0,
            info_gain: 0.0,
            relevance: 0.0,
            confidence: 1.0,
            cost: 0.0,
            risk: 0.0,
            context: HashMap::new(),
        }
    }

    pub fn is_stop(&self) -> bool {
        self.action_type == ActionType::Stop
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_planned_action_serialization() {
        let action = PlannedAction::new(
            ActionType::XssAnalysis,
            "dalfox",
            "http://target.local:8888/search?q=test",
            "Parameterized endpoint with reflection evidence",
            0.874,
        );

        let json = serde_json::to_string_pretty(&action).unwrap();
        assert!(json.contains("\"action_type\": \"xss_analysis\""));
        assert!(json.contains("\"tool\": \"dalfox\""));
        assert!(json.contains("\"target\": \"http://target.local:8888/search?q=test\""));
        assert!(json.contains("\"reason\": \"Parameterized endpoint with reflection evidence\""));
        assert!(json.contains("\"score\": 0.87"));

        let deserialized: PlannedAction = serde_json::from_str(&json).unwrap();
        assert_eq!(deserialized.action_type, ActionType::XssAnalysis);
        assert_eq!(deserialized.score, 0.87);
        assert!(!deserialized.is_stop());
    }

    #[test]
    fn test_stop_action() {
        let stop = PlannedAction::stop("No valuable unexplored surface");
        assert!(stop.is_stop());
        assert_eq!(stop.action_type, ActionType::Stop);
        assert_eq!(stop.score, 0.0);
    }
}
